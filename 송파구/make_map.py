dong_cnt = {}

coords_list = []
for _, row in units.iterrows():
    name = row['단지명']
    dong = row['읍면동']
    if name in known_coords:
        lat, lng = known_coords[name]
    else:
        base = dong_base.get(dong, (37.505, 127.110))
        cnt = dong_cnt.get(dong, 0)
        dong_cnt[dong] = cnt + 1
        angle = cnt * 137.5 * math.pi / 180
        r = 0.0008 * (1 + cnt // 8)
        lat = base[0] + r * math.cos(angle)
        lng = base[1] + r * math.sin(angle)
    coords_list.append((lat, lng))

units['lat'] = [c[0] for c in coords_list]
units['lng'] = [c[1] for c in coords_list]

rows = []
for _, row in units.iterrows():
    yr = row['연도']
    if yr < 1990:   color, bg = '#c0392b', '#fde8e8'
    elif yr < 2000: color, bg = '#d35400', '#fef0e0'
    elif yr < 2010: color, bg = '#1e8449', '#e8f8ee'
    elif yr < 2020: color, bg = '#1a5276', '#e8f2fd'
    else:           color, bg = '#6c3483', '#f2e8fd'

    rows.append({
        'name': row['단지명'],
        'yr2': str(row['연도'])[2:],
        'yr_full': str(row['사용승인일'])[:7],
        'units': int(row['총세대수']),
        'lat': row['lat'],
        'lng': row['lng'],
        'color': color,
        'bg': bg,
    })

print(json.dumps(rows, ensure_ascii=False))
